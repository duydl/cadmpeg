from pathlib import Path
import argparse,json,math
import vtk
parser=argparse.ArgumentParser()
parser.add_argument('directory',type=Path)
parser.add_argument('--offscreen',action='store_true')
args=parser.parse_args()
p=args.directory.resolve()
manifest=json.loads((p/'manifest.json').read_text())
window=vtk.vtkRenderWindow()
window.SetWindowName('FTC-07 | OpenCascade STEP comparison')
window.SetSize(1800,900)
window.SetMultiSamples(4)
window.SetNumberOfLayers(2)
window.SetOffScreenRendering(args.offscreen)
camera=vtk.vtkCamera()
camera.ParallelProjectionOn()
renderers=[]
for i,info in enumerate(manifest):
 renderer=vtk.vtkRenderer()
 renderer.SetViewport(i/3,0,(i+1)/3,1)
 renderer.SetBackground(.055,.073,.095)
 renderer.SetActiveCamera(camera)
 window.AddRenderer(renderer)
 reader=vtk.vtkSTLReader()
 reader.SetFileName(str(p/info['mesh']))
 reader.Update()
 normal=vtk.vtkPolyDataNormals()
 normal.SetInputConnection(reader.GetOutputPort())
 normal.SetFeatureAngle(35)
 mapper=vtk.vtkPolyDataMapper()
 mapper.SetInputConnection(normal.GetOutputPort())
 mapper.ScalarVisibilityOff()
 actor=vtk.vtkActor()
 actor.SetMapper(mapper)
 actor.GetProperty().SetColor(.77,.81,.85)
 actor.GetProperty().SetAmbient(.25)
 actor.GetProperty().SetDiffuse(.7)
 actor.GetProperty().SetSpecular(.15)
 actor.GetProperty().SetSpecularPower(24)
 renderer.AddActor(actor)
 overlay=vtk.vtkRenderer()
 overlay.SetLayer(1)
 overlay.SetViewport(renderer.GetViewport())
 overlay.InteractiveOff()
 window.AddRenderer(overlay)
 def label(text,y,size,color):
  actor=vtk.vtkTextActor()
  actor.SetInput(text)
  actor.GetTextProperty().SetFontSize(size)
  actor.GetTextProperty().SetColor(*color)
  actor.GetPositionCoordinate().SetCoordinateSystemToNormalizedViewport()
  actor.GetPositionCoordinate().SetValue(.035,y)
  overlay.AddActor2D(actor)
 label(info['label'],.95,22,(.94,.96,.98))
 label(str(info['shell_faces'])+' shell faces',.91,18,(.73,.79,.85))
 if i==1:
  label('304 solid faces + 2 sheet faces',.875,17,(.73,.79,.85))
 if info['invalid_shell_faces']:
  label(str(info['invalid_shell_faces'])+' invalid shell faces',.875,17,(1,.65,.49))
 if info['unmeshed_faces']:
  label(str(info['unmeshed_faces'])+' faces unmeshed',.84,16,(.8,.72,.61))
 label('OpenCascade tessellation | 0.1 mm',.055,15,(.62,.70,.77))
 label('Public NIST FTC-07 | shared orthographic camera',.025,12,(.62,.70,.77))
 renderers.append(renderer)
 if i==0:
  bounds=reader.GetOutput().GetBounds()
  center=tuple((bounds[2*k]+bounds[2*k+1])/2 for k in range(3))
  diagonal=math.sqrt(sum((bounds[2*k+1]-bounds[2*k])**2 for k in range(3)))
def set_view(direction):
 camera.SetFocalPoint(*center)
 camera.SetPosition(*(a+diagonal*b for a,b in zip(center,direction)))
 camera.SetViewUp(0,0,1)
 camera.SetParallelScale(diagonal*.80)
 for renderer in renderers:renderer.ResetCameraClippingRange()
 window.Render()
def screenshot(name):
 window.Render()
 capture=vtk.vtkWindowToImageFilter()
 capture.SetInput(window)
 capture.SetInputBufferTypeToRGB()
 capture.ReadFrontBufferOff()
 capture.Update()
 writer=vtk.vtkPNGWriter()
 writer.SetFileName(str(p/name))
 writer.SetInputConnection(capture.GetOutputPort())
 writer.Write()
 print(p/name,flush=True)
interactor=vtk.vtkRenderWindowInteractor()
interactor.SetRenderWindow(window)
interactor.SetInteractorStyle(vtk.vtkInteractorStyleTrackballCamera())
def keys(obj,event):
 key=obj.GetKeySym().lower()
 directions={'1':(1,-1,.8),'2':(0,-1,0),'3':(1,1,.8)}
 if key in directions:set_view(directions[key])
 elif key=='s':screenshot('ftc07-current.png')
interactor.AddObserver('KeyPressEvent',keys)
interactor.Initialize()
for name,direction in [('ftc07-isometric.png',(1,-1,.8)),('ftc07-front.png',(0,-1,0)),('ftc07-back.png',(1,1,.8))]:
 set_view(direction)
 screenshot(name)
set_view((1,1,.8))
(p/'viewer-ready.json').write_text(json.dumps({'ready':True,'shared_camera':True,'renderer':window.GetClassName()})+'\n')
if not args.offscreen:interactor.Start()
